/**
 * Extract numeric claims from text
 */
function extractNumericClaims(
  text: string
): Array<{ value: number; unit?: string; context: string }> {
  const claims: Array<{ value: number; unit?: string; context: string }> = [];

  // Match percentages
  const percentMatches = text.match(/(\d+(?:\.\d+)?)\s*%/g);
  if (percentMatches) {
    for (const match of percentMatches) {
      const value = parseFloat(match);
      // Flag unusually high percentages as potential hallucinations
      if (value > 100 || (value > 50 && !text.toLowerCase().includes('up to'))) {
        claims.push({ value, unit: '%', context: match });
      }
    }
  }

  // Match dollar amounts
  const dollarMatches = text.match(/\$(\d+(?:,\d{3})*(?:\.\d{2})?)/g);
  if (dollarMatches) {
    for (const match of dollarMatches) {
      const value = parseFloat(match.replace(/[$,]/g, ''));
      claims.push({ value, unit: '$', context: match });
    }
  }

  // Match time claims
  const timeMatches = text.match(/(\d+(?:\.\d+)?)\s*(days?|weeks?|months?|hours?)/gi);
  if (timeMatches) {
    for (const match of timeMatches) {
      const value = parseFloat(match);
      claims.push({ value, context: match });
    }
  }

  return claims;
}

/**
 * Complete validation pipeline
 */
export function validateCompleteProposal(
  proposal: ProposalResult,
  findings: FindingRuntime[]
): ValidationOutput {
  const proposalValidation = validateProposalStructure(proposal);
  const citationValidation = validateCitations(proposal, findings);
  const hallucinationDetection = detectHallucinations(proposal, findings);

  const overallValid =
    proposalValidation.valid &&
    citationValidation.valid &&
    !hallucinationDetection.hasHallucinations;
  const qualityScore = hallucinationDetection.confidenceScore;

  return {
    overallValid,
    proposalValidation,
    citationValidation,
    hallucinationDetection,
    qualityScore,
  };
}
