/**
 * Validate complete proposal structure
 */
export function validateProposalStructure(proposal: unknown): ValidationResult {
  try {
    ProposalResultSchema.parse(proposal);
    return {
      valid: true,
      errors: [],
      warnings: [],
    };
  } catch (error) {
    if (error instanceof z.ZodError) {
      return {
        valid: false,
        errors: error.errors.map((e) => `${e.path.join('.')}: ${e.message}`),
        warnings: [],
      };
    }
    return {
      valid: false,
      errors: ['Invalid proposal structure'],
      warnings: [],
    };
  }
}

/**
 * Validate citations in proposal against findings
 */
export function validateCitations(
  proposal: ProposalResult,
  findings: FindingRuntime[]
): CitationValidation {
  const errors: string[] = [];
  const missingCitations: string[] = [];
  const orphanedCitations: string[] = [];

  const findingIds = new Set(findings.map((f) => f.id));

  // Check tier citations
  for (const [tierName, tier] of Object.entries(proposal.tiers)) {
    for (const id of tier.findingIds) {
      if (!findingIds.has(id)) {
        missingCitations.push(`${tierName} tier references non-existent finding: ${id}`);
      }
    }
  }

  // Check pain clusters
  for (const cluster of proposal.painClusters) {
    for (const id of cluster.findingIds) {
      if (!findingIds.has(id)) {
        missingCitations.push(
          `Cluster "${cluster.rootCause}" references non-existent finding: ${id}`
        );
      }
    }
  }

  // Find orphaned findings (findings not referenced anywhere)
  const referencedIds = new Set<string>();
  Object.values(proposal.tiers).forEach((tier) => {
    tier.findingIds.forEach((id: string) => referencedIds.add(id));
  });
  proposal.painClusters.forEach((cluster) => {
    cluster.findingIds.forEach((id: string) => referencedIds.add(id));
  });

  findings.forEach((f) => {
    if (!referencedIds.has(f.id)) {
      orphanedCitations.push(`Finding "${f.title}" is not referenced in proposal`);
    }
  });

  return {
    valid: missingCitations.length === 0,
    errors: [...missingCitations, ...orphanedCitations],
    missingCitations,
    orphanedCitations,
  };
}

/**
 * Detect hallucinations in proposal content
 * P1-1 FIX: Enhanced with semantic similarity and numeric claim verification
 */
export function detectHallucinations(
  proposal: ProposalResult,
  findings: FindingRuntime[]
): HallucinationDetection {
  const flaggedClaims: Array<{
    claim: string;
    location: string;
    reason: string;
    severity: 'low' | 'medium' | 'high';
  }> = [];
  let totalClaims = 0;
  let supportedClaims = 0;

  // Build comprehensive finding reference data
  const findingRefs = findings.map((f) => ({
    id: f.id,
    title: (f.title || '').toLowerCase(),
    description: (f.description || '').toLowerCase(),
    metrics: f.metrics || {},
    impactScore: f.impactScore || 0,
    effortEstimate: f.effortEstimate || 'MEDIUM',
  }));

  // Check executive summary for supported claims
  const summary = proposal.executiveSummary;
  const summaryLower = summary.toLowerCase();

  // P1-1 FIX: Enhanced keyword matching with phrase extraction
  const keyPhrases = extractKeyPhrases(summary);

  for (const phrase of keyPhrases) {
    totalClaims++;
    let foundSupport = false;

    for (const finding of findingRefs) {
      // Check if phrase appears in finding title or description
      if (finding.title.includes(phrase) || finding.description.includes(phrase)) {
        foundSupport = true;
        supportedClaims++;
        break;
      }

      // Check for semantic similarity (simple word overlap)
      const phraseWords = phrase.split(/\s+/).filter((w) => w.length > 3);
      const findingWords = `${finding.title} ${finding.description}`.split(/\s+/);
      const overlap = phraseWords.filter((w) => findingWords.includes(w)).length;

      if (phraseWords.length > 0 && overlap / phraseWords.length >= 0.5) {
        foundSupport = true;
        supportedClaims++;
        break;
      }
    }

    if (!foundSupport && phrase.length > 5) {
      // Check if it's a generic statement (acceptable without specific finding)
      const genericPhrases = [
        'our team',
        'we will',
        'our analysis',
        'this proposal',
        'your business',
        'online presence',
      ];
      const isGeneric = genericPhrases.some((gp) => phrase.includes(gp));

      if (!isGeneric) {
        flaggedClaims.push({
          claim: `Phrase "${phrase.substring(0, 50)}${phrase.length > 50 ? '...' : ''}" lacks clear finding support`,
          location: 'executiveSummary',
          reason: 'Claim may not be grounded in audit findings',
          severity: 'medium',
        });
      } else {
        // Generic phrases count as supported
        supportedClaims++;
      }
    }
  }

  // P1-1 FIX: Enhanced numeric claim verification
  const numericClaims = extractNumericClaims(summary);

  for (const claim of numericClaims) {
    totalClaims++;
    let foundSupport = false;

    // Check if number appears in any finding metrics
    for (const finding of findingRefs) {
      const metricsValues = Object.values(finding.metrics).filter(
        (v) => typeof v === 'number'
      ) as number[];

      // Allow 10% tolerance for rounded numbers
      for (const metricValue of metricsValues) {
        if (Math.abs(metricValue - claim.value) / Math.max(metricValue, 1) <= 0.1) {
          foundSupport = true;
          supportedClaims++;
          break;
        }
      }

      // Check impact score matches
      if (claim.value === finding.impactScore || claim.value === Math.round(finding.impactScore)) {
        foundSupport = true;
        supportedClaims++;
        break;
      }
    }

    if (!foundSupport) {
      flaggedClaims.push({
        claim: `Numeric claim "${claim.value}${claim.unit || ''}" lacks supporting evidence in findings`,
        location: 'executiveSummary',
        reason: 'Potential fabricated statistic',
        severity: 'high',
      });
    }
  }

  // Check tier descriptions for unsubstantiated claims
  for (const [tierName, tier] of Object.entries(proposal.tiers)) {
    const tierText = `${tier.name} ${tier.description}`.toLowerCase();

    // Check for guarantee language
    const guaranteePatterns = [
      /\bguaranteed?\b/gi,
      /\bwill\s+(100%|definitely|certainly)\b/gi,
      /\brisk[- ]?free\b/gi,
    ];

    for (const pattern of guaranteePatterns) {
      if (pattern.test(tierText)) {
        flaggedClaims.push({
          claim: `Tier ${tierName} contains potential guarantee language`,
          location: `tiers.${tierName}`,
          reason: 'Guarantees may create legal liability',
          severity: 'high',
        });
      }
    }
  }

  const confidenceScore =
    totalClaims > 0 ? Math.max(0, Math.min(1, supportedClaims / totalClaims)) : 1;

  return {
    hasHallucinations: flaggedClaims.length > 0,
    flaggedClaims,
    confidenceScore,
  };
}

