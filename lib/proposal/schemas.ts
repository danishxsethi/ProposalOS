// Runtime Finding type - extends Prisma Finding with relaxed types for runtime flexibility
// The metrics field uses Record<string, unknown> instead of JsonValue for easier runtime access
export type FindingRuntime = {
  // Core fields from Prisma Finding
  id: string;
  auditId: string;
  module: string;
  category: string;
  type: FindingType;
  title: string;
  description: string | null;
  evidence: unknown;
  // Relaxed metrics type for runtime flexibility
  metrics: Record<string, unknown>;
  impactScore: number;
  confidenceScore: number;
  effortEstimate: string | null;
  recommendedFix: unknown;
  manuallyEdited: boolean;
  excluded: boolean;
  confidenceLevel: string | null;
  createdAt: Date;
  tenantId: string;
};

